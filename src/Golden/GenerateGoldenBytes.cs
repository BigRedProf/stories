namespace BigRedProf.Stories.Golden
{
	/// <summary>
	/// Captures golden bytes from pre-BitStream stories.
	/// This program is the capture tool for <c>golden.txt</c>. It is not part of
	/// <c>stories.sln</c>. Run it from the repository before any BitStream change:
	/// <c>dotnet run --project src/Golden/GenerateGoldenBytes.csproj -- src/Golden/golden.txt</c>.
	/// </summary>
	internal static class GenerateGoldenBytes
	{
		#region constants
		private const string CatalogStoryId = "catalog/content";
		private const string LogStoryId = "catalog/logs";
		#endregion

		#region functions
		private static int Main(string[] args)
		{
			string outputPath = args.Length > 0 ? args[0] : "golden.txt";

			PiedPiper piedPiper = CreatePiedPiper();
			Code byteAligned = new Code(new byte[] { 0x42, 0x49, 0x47, 0x52, 0x45, 0x44 });
			Code midByte = new Code("101");
			Code zeroBit = new Code(0);
			Code backToBack = new Code("101" + "01011" + "1" + "1111000");
			string[] backToBackOperations = new string[]
			{
				"WRITE 101",
				"WRITE 01011",
				"WRITE -",
				"WRITE 1",
				"WRITE 1111000"
			};

			if ((byteAligned.Length % 8) != 0)
				throw new InvalidOperationException("story-byte-aligned must end on a byte boundary.");

			if ((midByte.Length % 8) == 0)
				throw new InvalidOperationException("story-mid-byte must end partway through a byte.");

			if (zeroBit.Length != 0)
				throw new InvalidOperationException("story-zero-bit must be a 0-bit code.");

			if (ConcatenateOperations(backToBackOperations) != ToBits(backToBack))
				throw new InvalidOperationException("story-back-to-back operations are not the stored bits.");

			StringBuilder manifest = new StringBuilder();
			manifest.AppendLine("# Golden bytes captured from stories before the BitStream change.");
			manifest.AppendLine("# Generated by src/Golden/GenerateGoldenBytes.cs against pre-BitStream main.");
			manifest.AppendLine("# Do not edit. Any later diff to this file fails review.");
			manifest.AppendLine("#");
			manifest.AppendLine("# Samples are the bytes stories stores or encodes: story entries, the catalog");
			manifest.AppendLine("# file a scribe writes, list and pack-rat encodings, logging models, and the");
			manifest.AppendLine("# codes a backup hands to a tape. CodeWriter output matched these packed bytes.");
			manifest.AppendLine();

			WriteStoryEntry(manifest, piedPiper, "story-byte-aligned", byteAligned, new string[0]);
			WriteStoryEntry(manifest, piedPiper, "story-mid-byte", midByte, new string[0]);
			WriteStoryEntry(manifest, piedPiper, "story-zero-bit", zeroBit, new string[0]);
			WriteStoryEntry(manifest, piedPiper, "story-back-to-back", backToBack, backToBackOperations);

			Code[] catalogThings = new Code[] { byteAligned, midByte, zeroBit, backToBack };
			WriteCatalog(manifest, piedPiper, catalogThings);

			LogEntryProperty subject = new LogEntryProperty()
			{
				Name = "Subject",
				Value = "golden"
			};
			LogEntryProperty timestamp = new LogEntryProperty()
			{
				Name = "__Timestamp__",
				Value = "1976-06-23"
			};
			WriteLogProperty(manifest, piedPiper, subject);

			LogEntry information = new LogEntry()
			{
				LogName = "stories.golden",
				EventId = 7,
				EventName = "Golden",
				Level = LogLevel.Information,
				Message = "hello",
				Properties = new List<LogEntryProperty>() { subject, timestamp }
			};
			WriteLogEntry(manifest, piedPiper, "log-entry", information);

			LogEntry failure = new LogEntry()
			{
				LogName = "stories.golden",
				EventId = 4,
				EventName = null,
				Level = LogLevel.Error,
				Message = "boom",
				Properties = new List<LogEntryProperty>()
			};
			WriteLogEntry(manifest, piedPiper, "log-entry-null-event", failure);

			// BackupEngine's bookmark after the four catalog records is 4: the last
			// story offset is 3, and the checkpoint stores that offset plus one.
			WriteCheckpoint(manifest, piedPiper, "backup-checkpoint-0", 0L);
			WriteCheckpoint(manifest, piedPiper, "backup-checkpoint-4", 4L);

			File.WriteAllText(outputPath, manifest.ToString().Replace("\r\n", "\n"));
			Console.WriteLine("Wrote " + outputPath);
			return 0;
		}

		private static void WriteStoryEntry(
			StringBuilder manifest,
			PiedPiper piedPiper,
			string name,
			Code thing,
			string[] operations
		)
		{
			string bits = ToBits(thing);
			Code rebuilt = bits == "-" ? new Code(0) : new Code(bits);
			if (rebuilt != thing)
				throw new InvalidOperationException(name + " bit string does not round-trip.");

			StoryThing storyThing = new StoryThing()
			{
				Offset = 0,
				Thing = thing
			};
			Code packed = piedPiper.PackModel<StoryThing>(storyThing, StoriesSchemaId.StoryThing);
			RequireSameBytes(
				name + " story thing",
				packed,
				WriteWire(piedPiper.GetPackRat<StoryThing>(StoriesSchemaId.StoryThing), storyThing)
			);
			StoryThing unpacked = piedPiper.UnpackModel<StoryThing>(
				new Code(packed.ToByteArray(), packed.Length),
				StoriesSchemaId.StoryThing
			);
			if (unpacked.Offset != 0 || unpacked.Thing != thing)
				throw new InvalidOperationException(name + " story thing does not round-trip.");

			byte[] payload = piedPiper.SaveCodeToByteArray(packed);
			if (piedPiper.LoadCodeFromByteArray(payload) != packed)
				throw new InvalidOperationException(name + " payload does not round-trip.");

			Code tapeCode = piedPiper.PackModel(thing, CoreSchema.Code);
			RequireSameBytes(
				name + " tape code",
				tapeCode,
				WriteWire(piedPiper.GetPackRat<Code>(CoreSchema.Code), thing)
			);
			if (piedPiper.UnpackModel<Code>(new Code(tapeCode.ToByteArray(), tapeCode.Length), CoreSchema.Code) != thing)
				throw new InvalidOperationException(name + " tape code does not round-trip.");

			if (name == "story-mid-byte")
			{
				if ((packed.Length % 8) == 0 || (tapeCode.Length % 8) == 0)
					throw new InvalidOperationException(name + " stored encoding must end partway through a byte.");
			}

			ListOfThings listOfThings = new ListOfThings()
			{
				Things = new List<Code>() { thing }
			};
			Code packedList = piedPiper.PackModel<ListOfThings>(listOfThings, StoriesSchemaId.ListOfThings);
			RequireSameBytes(
				name + " list of things",
				packedList,
				WriteWire(piedPiper.GetPackRat<ListOfThings>(StoriesSchemaId.ListOfThings), listOfThings)
			);

			ListOfStoryThings listOfStoryThings = new ListOfStoryThings()
			{
				StoryThings = new List<StoryThing>() { storyThing }
			};
			Code packedStories = piedPiper.PackModel<ListOfStoryThings>(
				listOfStoryThings,
				StoriesSchemaId.ListOfStoryThings
			);
			RequireSameBytes(
				name + " list of story things",
				packedStories,
				WriteWire(
					piedPiper.GetPackRat<ListOfStoryThings>(StoriesSchemaId.ListOfStoryThings),
					listOfStoryThings
				)
			);

			WrittenFile file = WriteStoryFile(piedPiper, CatalogStoryId, new Code[] { thing }, name);
			if (file.Things.Count != 1 || file.Things[0].Offset != 0 || file.Things[0].Thing != thing)
				throw new InvalidOperationException(name + " story file does not round-trip.");

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND story-entry");
			foreach (string operation in operations)
				manifest.AppendLine("OP " + operation);
			manifest.AppendLine("BITS " + bits);
			manifest.AppendLine("BIT_LENGTH " + thing.Length.ToString(CultureInfo.InvariantCulture));
			AppendCode(manifest, "STORY_THING", packed);
			manifest.AppendLine("PAYLOAD_HEX " + ToHex(payload));
			manifest.AppendLine("STORY_ID " + CatalogStoryId);
			manifest.AppendLine("FILE_NAME " + file.FileName);
			manifest.AppendLine("FILE_HEX " + ToHex(file.Bytes));
			AppendCode(manifest, "LIST_OF_THINGS", packedList);
			AppendCode(manifest, "LIST_OF_STORY_THINGS", packedStories);
			AppendCode(manifest, "TAPE_CODE", tapeCode);
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void WriteCatalog(StringBuilder manifest, PiedPiper piedPiper, Code[] things)
		{
			WrittenFile file = WriteStoryFile(piedPiper, CatalogStoryId, things, "catalog-content");
			if (file.Things.Count != things.Length)
				throw new InvalidOperationException("catalog-content did not round-trip every thing.");

			List<StoryThing> storyThings = new List<StoryThing>();
			for (int i = 0; i < things.Length; i++)
			{
				if (file.Things[i].Offset != i || file.Things[i].Thing != things[i])
					throw new InvalidOperationException("catalog-content offset " + i.ToString(CultureInfo.InvariantCulture) + " changed.");

				storyThings.Add(file.Things[i]);
			}

			ListOfThings listOfThings = new ListOfThings()
			{
				Things = new List<Code>(things)
			};
			Code packedList = piedPiper.PackModel<ListOfThings>(listOfThings, StoriesSchemaId.ListOfThings);
			RequireSameBytes(
				"catalog-content list of things",
				packedList,
				WriteWire(piedPiper.GetPackRat<ListOfThings>(StoriesSchemaId.ListOfThings), listOfThings)
			);

			ListOfStoryThings listOfStoryThings = new ListOfStoryThings()
			{
				StoryThings = storyThings
			};
			Code packedStories = piedPiper.PackModel<ListOfStoryThings>(
				listOfStoryThings,
				StoriesSchemaId.ListOfStoryThings
			);
			RequireSameBytes(
				"catalog-content list of story things",
				packedStories,
				WriteWire(
					piedPiper.GetPackRat<ListOfStoryThings>(StoriesSchemaId.ListOfStoryThings),
					listOfStoryThings
				)
			);

			manifest.AppendLine("SAMPLE catalog-content");
			manifest.AppendLine("KIND catalog-file");
			manifest.AppendLine("STORY_ID " + CatalogStoryId);
			manifest.AppendLine("FILE_NAME " + file.FileName);
			manifest.AppendLine("COUNT " + things.Length.ToString(CultureInfo.InvariantCulture));
			for (int i = 0; i < things.Length; i++)
			{
				string index = i.ToString(CultureInfo.InvariantCulture);
				manifest.AppendLine("ITEM " + index + " BITS " + ToBits(things[i]));
				manifest.AppendLine("ITEM " + index + " BIT_LENGTH " + things[i].Length.ToString(CultureInfo.InvariantCulture));
			}

			manifest.AppendLine("FILE_HEX " + ToHex(file.Bytes));
			AppendCode(manifest, "LIST_OF_THINGS", packedList);
			AppendCode(manifest, "LIST_OF_STORY_THINGS", packedStories);
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void WriteLogProperty(StringBuilder manifest, PiedPiper piedPiper, LogEntryProperty property)
		{
			Code packed = piedPiper.PackModel<LogEntryProperty>(property, StoriesLoggingSchemaId.LogEntryProperty);
			RequireSameBytes(
				"log-entry-property",
				packed,
				WriteWire(piedPiper.GetPackRat<LogEntryProperty>(StoriesLoggingSchemaId.LogEntryProperty), property)
			);
			LogEntryProperty unpacked = piedPiper.UnpackModel<LogEntryProperty>(
				new Code(packed.ToByteArray(), packed.Length),
				StoriesLoggingSchemaId.LogEntryProperty
			);
			if (unpacked.Name != property.Name || unpacked.Value != property.Value)
				throw new InvalidOperationException("log-entry-property does not round-trip.");

			manifest.AppendLine("SAMPLE log-entry-property");
			manifest.AppendLine("KIND log-property");
			manifest.AppendLine("NAME " + property.Name);
			manifest.AppendLine("VALUE " + property.Value);
			AppendCode(manifest, "ENTRY", packed);
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void WriteLogEntry(StringBuilder manifest, PiedPiper piedPiper, string name, LogEntry entry)
		{
			Code packedEntry = piedPiper.PackModel<LogEntry>(entry, StoriesLoggingSchemaId.LogEntry);
			RequireSameBytes(
				name + " entry",
				packedEntry,
				WriteWire(piedPiper.GetPackRat<LogEntry>(StoriesLoggingSchemaId.LogEntry), entry)
			);
			LogEntry unpackedEntry = piedPiper.UnpackModel<LogEntry>(
				new Code(packedEntry.ToByteArray(), packedEntry.Length),
				StoriesLoggingSchemaId.LogEntry
			);
			if (!SameLogEntry(entry, unpackedEntry))
				throw new InvalidOperationException(name + " does not round-trip.");

			// StoryLogger stores the datum wrapper, not the bare log entry.
			Datum datum = piedPiper.PackDatum(entry, StoriesLoggingSchemaId.LogEntry);
			Code packedDatum = piedPiper.PackModel<Datum>(datum, CoreSchema.Datum);
			RequireSameBytes(
				name + " datum",
				packedDatum,
				WriteWire(piedPiper.GetPackRat<Datum>(CoreSchema.Datum), datum)
			);
			Datum unpackedDatum = piedPiper.UnpackModel<Datum>(
				new Code(packedDatum.ToByteArray(), packedDatum.Length),
				CoreSchema.Datum
			);
			LogEntry fromDatum = unpackedDatum.Unpack<LogEntry>(piedPiper);
			if (!SameLogEntry(entry, fromDatum))
				throw new InvalidOperationException(name + " datum does not round-trip.");

			StoryThing storyThing = new StoryThing()
			{
				Offset = 0,
				Thing = packedDatum
			};
			Code packedStoryThing = piedPiper.PackModel<StoryThing>(storyThing, StoriesSchemaId.StoryThing);
			RequireSameBytes(
				name + " story thing",
				packedStoryThing,
				WriteWire(piedPiper.GetPackRat<StoryThing>(StoriesSchemaId.StoryThing), storyThing)
			);
			byte[] payload = piedPiper.SaveCodeToByteArray(packedStoryThing);
			WrittenFile file = WriteStoryFile(piedPiper, LogStoryId, new Code[] { packedDatum }, name);
			if (file.Things.Count != 1 || file.Things[0].Thing != packedDatum)
				throw new InvalidOperationException(name + " log file does not round-trip.");

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND log-entry");
			manifest.AppendLine("LOG_NAME " + entry.LogName);
			manifest.AppendLine("EVENT_ID " + entry.EventId.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine("EVENT_NAME " + (entry.EventName == null ? "-" : entry.EventName));
			manifest.AppendLine("LEVEL " + entry.Level.ToString());
			manifest.AppendLine("MESSAGE " + entry.Message);
			foreach (LogEntryProperty property in entry.Properties)
				manifest.AppendLine("PROPERTY " + property.Name + " " + property.Value);
			AppendCode(manifest, "ENTRY", packedEntry);
			AppendCode(manifest, "DATUM", packedDatum);
			AppendCode(manifest, "STORY_THING", packedStoryThing);
			manifest.AppendLine("PAYLOAD_HEX " + ToHex(payload));
			manifest.AppendLine("STORY_ID " + LogStoryId);
			manifest.AppendLine("FILE_NAME " + file.FileName);
			manifest.AppendLine("FILE_HEX " + ToHex(file.Bytes));
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static void WriteCheckpoint(StringBuilder manifest, PiedPiper piedPiper, string name, long offset)
		{
			Code packed = piedPiper.PackModel<long>(offset, CoreSchema.Int64);
			RequireSameBytes(
				name,
				packed,
				WriteWire(piedPiper.GetPackRat<long>(CoreSchema.Int64), offset)
			);
			long unpacked = piedPiper.UnpackModel<long>(new Code(packed.ToByteArray(), packed.Length), CoreSchema.Int64);
			if (unpacked != offset)
				throw new InvalidOperationException(name + " does not round-trip.");

			manifest.AppendLine("SAMPLE " + name);
			manifest.AppendLine("KIND backup-checkpoint");
			manifest.AppendLine("OFFSET " + offset.ToString(CultureInfo.InvariantCulture));
			AppendCode(manifest, "CHECKPOINT", packed);
			manifest.AppendLine("END");
			manifest.AppendLine();
		}

		private static WrittenFile WriteStoryFile(PiedPiper piedPiper, string storyIdText, Code[] things, string name)
		{
			TextTrail storyId = TextTrailSerializer.ParseTextRepresentation(storyIdText);
			string expectedName = TextTrailSerializer.ToMultihashString(storyId) + ".story";
			string root = Path.Combine(Path.GetTempPath(), "BigRedProf.Stories.Golden", name);
			if (Directory.Exists(root))
				Directory.Delete(root, true);

			try
			{
				using (FileScribe scribe = new FileScribe(root, storyId, piedPiper))
				{
					scribe.RecordSomething(things);
				}

				string[] files = Directory.GetFiles(root);
				string? storyPath = null;
				for (int i = 0; i < files.Length; i++)
				{
					if (files[i].EndsWith(".story", StringComparison.Ordinal))
					{
						if (storyPath != null)
							throw new InvalidOperationException(name + " wrote more than one story file.");

						storyPath = files[i];
					}
				}

				if (storyPath == null)
					throw new InvalidOperationException(name + " did not write a story file.");

				string fileName = Path.GetFileName(storyPath);
				if (fileName != expectedName)
					throw new InvalidOperationException(name + " file name is not the story id hash.");

				byte[] first = File.ReadAllBytes(storyPath);
				using (FileScribe scribe = new FileScribe(root + "-again", storyId, piedPiper))
				{
					scribe.RecordSomething(things);
				}

				byte[] second = File.ReadAllBytes(Path.Combine(root + "-again", fileName));
				if (!BytesEqual(first, second))
					throw new InvalidOperationException(name + " story file is not deterministic.");

				FileStoryteller storyteller = new FileStoryteller(root, storyId, piedPiper);
				List<StoryThing> readBack = new List<StoryThing>();
				while (storyteller.HasSomethingForMe)
					readBack.Add(storyteller.TellMeSomething());

				return new WrittenFile(fileName, first, readBack);
			}
			finally
			{
				if (Directory.Exists(root))
					Directory.Delete(root, true);

				if (Directory.Exists(root + "-again"))
					Directory.Delete(root + "-again", true);
			}
		}

		private static PiedPiper CreatePiedPiper()
		{
			PiedPiper piedPiper = new PiedPiper();
			piedPiper.RegisterCorePackRats();
			piedPiper.RegisterPackRats(typeof(StoryThing).Assembly);
			piedPiper.RegisterPackRats(typeof(LogEntry).Assembly);
			return piedPiper;
		}

		private static byte[] WriteWire<T>(PackRat<T> packRat, T model)
		{
			MemoryStream stream = new MemoryStream();
			using (CodeWriter writer = new CodeWriter(stream))
			{
				packRat.PackModel(writer, model);
			}

			return stream.ToArray();
		}

		private static void RequireSameBytes(string label, Code packed, byte[] wire)
		{
			if (!BytesEqual(packed.ToByteArray(), wire))
				throw new InvalidOperationException(label + " CodeWriter bytes differ from the packed code.");
		}

		private static bool SameLogEntry(LogEntry expected, LogEntry actual)
		{
			if (actual == null)
				return false;

			if (expected.LogName != actual.LogName)
				return false;

			if (expected.EventId != actual.EventId)
				return false;

			if (expected.EventName != actual.EventName)
				return false;

			if (expected.Level != actual.Level)
				return false;

			if (expected.Message != actual.Message)
				return false;

			if (expected.Properties == null || actual.Properties == null)
				return expected.Properties == actual.Properties;

			if (expected.Properties.Count != actual.Properties.Count)
				return false;

			for (int i = 0; i < expected.Properties.Count; i++)
			{
				if (expected.Properties[i].Name != actual.Properties[i].Name)
					return false;

				if (expected.Properties[i].Value != actual.Properties[i].Value)
					return false;
			}

			return true;
		}

		private static string ConcatenateOperations(string[] operations)
		{
			StringBuilder builder = new StringBuilder();
			foreach (string operation in operations)
			{
				if (!operation.StartsWith("WRITE ", StringComparison.Ordinal))
					throw new InvalidOperationException("Story samples only write. Got '" + operation + "'.");

				string written = operation.Substring("WRITE ".Length);
				if (written == "-")
					continue;

				builder.Append(written);
			}

			string bits = builder.ToString();
			if (bits.Length == 0)
				return "-";

			return bits;
		}

		private static void AppendCode(StringBuilder manifest, string name, Code code)
		{
			manifest.AppendLine(name + "_BIT_LENGTH " + code.Length.ToString(CultureInfo.InvariantCulture));
			manifest.AppendLine(name + "_HEX " + ToHex(code.ToByteArray()));
		}

		private static string ToBits(Code code)
		{
			if (code.Length == 0)
				return "-";

			char[] chars = new char[code.Length];
			for (int i = 0; i < code.Length; i++)
				chars[i] = code[i] == 0 ? '0' : '1';

			return new string(chars);
		}

		private static string ToHex(byte[] bytes)
		{
			if (bytes.Length == 0)
				return "-";

			StringBuilder builder = new StringBuilder(bytes.Length * 2);
			for (int i = 0; i < bytes.Length; i++)
				builder.Append(bytes[i].ToString("x2", CultureInfo.InvariantCulture));

			return builder.ToString();
		}

		private static bool BytesEqual(byte[] left, byte[] right)
		{
			if (left.Length != right.Length)
				return false;

			for (int i = 0; i < left.Length; i++)
			{
				if (left[i] != right[i])
					return false;
			}

			return true;
		}
		#endregion

		#region nested types
		private sealed class WrittenFile
		{
			public WrittenFile(string fileName, byte[] bytes, List<StoryThing> things)
			{
				FileName = fileName;
				Bytes = bytes;
				Things = things;
			}

			public string FileName
			{
				get;
			}

			public byte[] Bytes
			{
				get;
			}

			public List<StoryThing> Things
			{
				get;
			}
		}
		#endregion
	}
